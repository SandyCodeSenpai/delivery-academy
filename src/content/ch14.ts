const SIGNER_TS = L(
  "import { createHmac } from \"node:crypto\";",
  "",
  "export type CdnName = \"fastly\" | \"cloudfront\" | \"akamai\";",
  "",
  "export interface CdnSigner {",
  "  readonly cdn: CdnName;",
  "  sign(path: string, expiresAtEpochSec: number): string;",
  "}",
  "",
  "// Illustrative HMAC signer. Real vendor formats differ (see Chapter 8).",
  "export class HmacPathSigner implements CdnSigner {",
  "  constructor(readonly cdn: CdnName, private kid: string, private key: Buffer) {}",
  "  sign(path: string, exp: number): string {",
  "    const mac = createHmac(\"sha256\", this.key)",
  "      .update(`${path}|${exp}|${this.kid}`).digest(\"hex\");",
  "    return `${path}?exp=${exp}&kid=${this.kid}&sig=${mac}`;",
  "  }",
  "}",
);

