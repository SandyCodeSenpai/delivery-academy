  "",
  "export function validate(next: SteeringConfig, prev: SteeringConfig): string[] {",
  "  const errs: string[] = [];",
  "  const entries = Object.entries(next.weights);",
  "  const total = entries.reduce((s, [, w]) => s + w, 0);",
  "  if (entries.length === 0) errs.push(\"no CDNs configured\");",
  "  if (total !== 100) errs.push(`weights sum to ${total}, expected 100`);",
  "  for (const [cdn, w] of entries) {",
  "    if (w < 0) errs.push(`${cdn}: negative weight`);",
  "    const step = Math.abs(w - (prev.weights[cdn] ?? 0));",
  "    if (step > 30) errs.push(`${cdn}: moves ${step} points in one change`);",
  "  }",
  "  if (next.version <= prev.version) errs.push(\"version must increase\");",
  "  return errs;",
  "}",
