/** Keep only the listed nodes (and the edges between them). Used to grow one diagram node by node. */
function grow(
  base: { nodes: FlowNode[]; edges: FlowEdge[]; direction?: "down" | "right" },
  show: string[] | "all",
  focus?: string[],
  flow?: string[],
): FlowSpec {
  const keep = show === "all" ? new Set(base.nodes.map((n) => n.id)) : new Set(show);
  const spec: FlowSpec = {
    nodes: base.nodes.filter((n) => keep.has(n.id)),
    edges: base.edges.filter((e) => keep.has(e.from) && keep.has(e.to)),
  };
  if (base.direction) spec.direction = base.direction;
  if (focus) spec.focus = focus;
  if (flow) spec.flow = flow;
  return spec;
}

