const VCL = [
  "sub vcl_recv {",
  "  declare local var.p STRING;",
  "  declare local var.exp STRING;",
  "  declare local var.sig STRING;",
  "  set var.p = urldecode(subfield(req.url.qs, \"p\", \"&\"));",
  "  set var.exp = subfield(req.url.qs, \"exp\", \"&\");",
  "  set var.sig = urldecode(subfield(req.url.qs, \"sig\", \"&\"));",
  "  if (!std.prefixof(req.url.path, var.p)) { error 403; }",
  "  if (time.is_after(now, std.integer2time(std.atoi(var.exp)))) { error 403; }",
  "  if (!digest.secure_is_equal(var.sig,",
  "      digest.hmac_sha256_base64(table.lookup(token_keys, \"current\"), var.p + \"|\" + var.exp))) {",
  "    error 403;",
  "  }",
  "  set req.url = querystring.filter(req.url, \"p\" + querystring.filtersep() + \"exp\" + querystring.filtersep() + \"sig\");",
  "}",
].join("\n");

const SIGNER = [
  "import { createHmac } from \"node:crypto\";",
  "",
  "export function signPrefix(prefix: string, ttlSec: number, key: Buffer): string {",
  "  const exp = Math.floor(Date.now() / 1000) + ttlSec;",
  "  const sig = createHmac(\"sha256\", key).update(`${prefix}|${exp}`).digest(\"base64\");",
  "  return `p=${encodeURIComponent(prefix)}&exp=${exp}&sig=${encodeURIComponent(sig)}`;",
  "}",
].join("\n");

